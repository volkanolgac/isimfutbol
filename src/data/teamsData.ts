export const recalculateStandingsFromFixtures = (
  teamsList: Team[] = INITIAL_TEAMS_DATA,
  fixturesList: LeagueFixture[] = []
): LeagueStanding[] => {
  const standingsMap: Record<string, LeagueStanding> = {};

  teamsList.forEach(team => {
    standingsMap[team.id] = {
      teamId: team.id,
      teamName: team.name,
      played: 0,
      won: 0,
      drawn: 0,
      lost: 0,
      goalsFor: 0,
      goalsAgainst: 0,
      goalDifference: 0,
      points: 0,
      form: [],
    };
  });

  const teamForms: Record<string, Array<'W' | 'D' | 'L'>> = {};
  teamsList.forEach(t => {
    teamForms[t.id] = [];
  });

  // Filter ONLY played fixtures, sorted chronologically by week
  const playedFixtures = fixturesList
    .filter(f => f.played && f.homeScore !== undefined && f.awayScore !== undefined)
    .sort((a, b) => a.week - b.week);

  playedFixtures.forEach(f => {
    const home = standingsMap[f.homeTeamId];
    const away = standingsMap[f.awayTeamId];
    if (!home || !away) return;

    const hScore = f.homeScore!;
    const aScore = f.awayScore!;

    const hWin = hScore > aScore;
    const draw = hScore === aScore;
    const aWin = aScore > hScore;

    // Home team stats
    home.played += 1;
    home.goalsFor += hScore;
    home.goalsAgainst += aScore;
    home.goalDifference += (hScore - aScore);

    if (hWin) {
      home.won += 1;
      home.points += 3;
      teamForms[f.homeTeamId].push('W');
    } else if (draw) {
      home.drawn += 1;
      home.points += 1;
      teamForms[f.homeTeamId].push('D');
    } else {
      home.lost += 1;
      teamForms[f.homeTeamId].push('L');
    }

    // Away team stats
    away.played += 1;
    away.goalsFor += aScore;
    away.goalsAgainst += hScore;
    away.goalDifference += (aScore - hScore);

    if (aWin) {
      away.won += 1;
      away.points += 3;
      teamForms[f.awayTeamId].push('W');
    } else if (draw) {
      away.drawn += 1;
      away.points += 1;
      teamForms[f.awayTeamId].push('D');
    } else {
      away.lost += 1;
      teamForms[f.awayTeamId].push('L');
    }
  });

  // Keep last 5 match results for form
  teamsList.forEach(t => {
    if (standingsMap[t.id]) {
      const fullForm = teamForms[t.id] || [];
      standingsMap[t.id].form = fullForm.slice(-5);
    }
  });

  return Object.values(standingsMap);
};


