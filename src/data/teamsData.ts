// Ensure all 18 teams have exactly 6 starters (1 GK + 5 outfield) and 5 bench players (1 GK + 4 outfield)
const VALID_FORMATIONS: Array<'2-2-1' | '2-1-2' | '1-3-1' | '3-1-1' | '1-2-2' | '2-3-0'> = [
  '2-2-1', '2-1-2', '1-3-1', '3-1-1', '1-2-2', '2-3-0'
];

export const INITIAL_TEAMS_DATA: Team[] = INITIAL_TEAMS.map((team, tIdx) => {
  const formation = VALID_FORMATIONS[tIdx % VALID_FORMATIONS.length];
  // Reorganize players: player 0 is GK, players 1-5 are outfield starters (6 starters total)
  // players 6-9 are outfield bench, player 10 is backup GK (5 bench total)
  const formattedPlayers: Player[] = team.players.map((p, idx) => ({
    ...p,
    isStarter: idx < 6,
  }));

  return {
    ...team,
    formation,
    players: formattedPlayers,
  };
});

